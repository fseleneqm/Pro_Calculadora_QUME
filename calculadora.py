# Distintas oepraciones aritméticas
# Suma
num1 = input("Introduce un número: ")
num2 = input("\nIntroduce otro número: ")


print("\nSuma")
suma = num1 + num2
print(f"\nResultado suma: {suma}")

print("\nResta")
resta = num1 - num2
print(f"\nResultado resta: {resta}")

print("\nMultiplicación")
mult = num1 * num2
print(f"\nResultado multiplicación: {mult}")

print("\nDivisión")
div = num1 / num2
print(f"\nResultado división: {div}")

print("\nPorcentaje")
porcentaje = num1 % num2
print(f"\nResultado porcentaje: {porcentaje}")